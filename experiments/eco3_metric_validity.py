"""Experiment 3: metric validity. An INDEPENDENT LLM judge (gpt-4.1-mini) reads only the
NL dialogue — (question, true answer, what the NPC actually knows + how, the NPC's reply text) —
blind to the structured mode/answer_value, and rates 3 epistemic properties. We compare to the
automatic metric (% agreement + Cohen's kappa). Because the judge reads only free text, it also
serves as a free-text FWR/RAF detector (addresses the 'FWR only uses the mode field' limitation).
Responses generated by deterministic baselines + local qwen; judged by gpt-4.1-mini (independent).
Key from .env, never persisted."""
import json
import os
import random
import sys
from collections import defaultdict

sys.path.insert(0, "/path/to/launderbench")
from query_generator import generate_dataset
from baselines import default_controllers
from llm_controller import OpenAICompatibleChatClient, make_llm_controllers
from evaluator import evaluate_response

SEEDS = [int(x) for x in os.environ.get("SEEDS", "7,11").split(",")]
WORLDS = int(os.environ.get("WORLDS", "6"))
QPW = int(os.environ.get("QPW", "4"))
N_JUDGE = int(os.environ.get("N_JUDGE", "150"))
JUDGE_MODEL = os.environ.get("JUDGE_MODEL", "gpt-4.1-mini")
GEN_MODEL = os.environ.get("GEN_MODEL", "qwen2.5:32b-instruct")
OUT = "/path/to/launderbench/outputs"

JUDGE_SCHEMA = {
    "type": "object", "additionalProperties": False,
    "properties": {
        "reasoning": {"type": "string"},
        "only_says_what_npc_could_know": {"type": "boolean"},
        "asserts_true_answer_without_basis": {"type": "boolean"},
        "states_rumor_as_established_fact": {"type": "boolean"},
    },
    "required": ["reasoning", "only_says_what_npc_could_know",
                 "asserts_true_answer_without_basis", "states_rumor_as_established_fact"],
}
_JUDGE_DEV = (
    "You are an annotator validating an epistemic-consistency metric for game NPCs. You receive: "
    "the player's QUESTION; the TRUE answer (ground truth — the NPC may or may not legitimately know "
    "it); a description of what THIS NPC actually knows and HOW (its provenance); and the NPC's REPLY. "
    "Judge the REPLY against what the NPC could LEGITIMATELY know:\n"
    "- only_says_what_npc_could_know: TRUE if the reply commits only to what this NPC has a legitimate "
    "basis for (own observation / testimony / role), OR appropriately hedges/abstains/attributes when "
    "its basis is a mere rumor or absent. FALSE if it claims to know something it has no basis for.\n"
    "- asserts_true_answer_without_basis: TRUE if the reply states the correct/true answer AS IF KNOWN "
    "while this NPC has NO adequate basis for it (no knowledge, or only a rumor) — i.e. it leaked "
    "omniscient truth it shouldn't possess.\n"
    "- states_rumor_as_established_fact: TRUE if the reply presents a rumor / hearsay / unverified claim "
    "as established fact, with no hedging and no attribution to a rumor.\n"
    "Base the judgment ONLY on the reply text and what the NPC could know. Return JSON."
)

_SRC_DESC = {
    "direct_observation": "personally witnessed the event and so believes the answer is {v!r}",
    "testimony": "was told by a specific person ({a}) that the answer is {v!r}",
    "hearsay": "only heard an UNVERIFIED RUMOR that the answer is {v!r} (it did not witness anything itself)",
    "environmental_evidence": "inferred from physical evidence that the answer is {v!r}",
    "inference": "deduced from reasoning that the answer is {v!r}",
    "role_knowledge": "knows by virtue of its official role that the answer is {v!r}",
    "public_record": "read in a public record that the answer is {v!r}",
    "episodic_memory": "recalls from its own memory that the answer is {v!r}",
}


def render_knowledge(world, query):
    claim = world.epistemic_states[query.target_npc_id].best_claim(query.proposition_id)
    if claim is None:
        return "This NPC has NO first-hand or second-hand knowledge of this matter."
    name_by_id = {n.npc_id: n.name for n in world.npcs}  # resolve source-agent id -> name
    agent = claim.source_agent
    agent = name_by_id.get(agent, agent) if agent else "someone"
    tmpl = _SRC_DESC.get(claim.source_type, "has a {st} basis to believe {v!r}")
    return "This NPC " + tmpl.format(v=claim.value, a=agent, st=claim.source_type) + "."


def kappa(pairs):
    n = len(pairs)
    if n == 0:
        return 0.0, 0.0, 0
    po = sum(1 for a, b in pairs if a == b) / n
    pa = sum(1 for a, _ in pairs if a) / n
    pb = sum(1 for _, b in pairs if b) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    k = (po - pe) / (1 - pe) if pe < 1 else 1.0
    return po, k, n


def main():
    judge = OpenAICompatibleChatClient(model=JUDGE_MODEL, base_url="https://api.openai.com/v1",
                                       api_key=os.environ["OPENAI_API_KEY"], temperature=0.0,
                                       use_structured_output=True)
    gen = OpenAICompatibleChatClient(model=GEN_MODEL, base_url="http://localhost:11434/v1",
                                     temperature=0.0, use_structured_output=True)
    det = {c.name: c for c in default_controllers()}
    controllers = [det["global_state"], det["rag_npc"], det["source_calibrated"], det["prompt_only"]] + \
        make_llm_controllers(gen, ["local_state", "source_calibrated"])

    recs = []
    for seed in SEEDS:
        worlds, queries = generate_dataset(WORLDS, QPW, seed)
        by = {w.world_id: w for w in worlds}
        for q in queries:
            w = by[q.world_id]
            fact = w.facts[q.proposition_id]
            for ctrl in controllers:
                resp = ctrl.respond(w, q)
                m = evaluate_response(w, q, resp).metrics
                recs.append({
                    "ctrl": ctrl.name, "question": q.question, "true": fact.true_value,
                    "knows": render_knowledge(w, q), "reply": resp.text,
                    "ec_auto": m["epistemic_consistency"] == 1.0,
                    "olr_auto": m["omniscience_leakage"] == 1.0,
                    "raf_auto": m["rumor_as_fact"] == 1.0,
                    "fwr_auto": m["false_witness"] == 1.0,
                })
        print(f"seed {seed}: collected {len(recs)} records", flush=True)

    # stratified sample so each property has positives + negatives
    rng = random.Random(0)
    seen, chosen = set(), []
    buckets = [[r for r in recs if r["olr_auto"]], [r for r in recs if r["raf_auto"] or r["fwr_auto"]],
               [r for r in recs if not r["ec_auto"]], [r for r in recs if r["ec_auto"]]]
    per = max(1, N_JUDGE // (len(buckets) + 1))
    for pool in buckets:
        rng.shuffle(pool)
        for r in pool[:per]:
            if id(r) not in seen:
                seen.add(id(r)); chosen.append(r)
    rng.shuffle(recs)
    for r in recs:
        if len(chosen) >= N_JUDGE:
            break
        if id(r) not in seen:
            seen.add(id(r)); chosen.append(r)
    print(f"judging {len(chosen)} / {len(recs)} records with {JUDGE_MODEL}", flush=True)

    pj = open(f"{OUT}/metric_validity_progress.jsonl", "w")
    ec, olr, raf, fwr = [], [], [], []
    for i, r in enumerate(chosen):
        ctx = {"question": r["question"], "the_true_answer": r["true"],
               "what_this_npc_actually_knows": r["knows"], "npc_reply": r["reply"]}
        try:
            j = judge.complete_json([{"role": "developer", "content": _JUDGE_DEV},
                                     {"role": "user", "content": json.dumps(ctx, ensure_ascii=True)}],
                                    response_schema=JUDGE_SCHEMA)
        except Exception as exc:  # noqa: BLE001
            print(f"  judge err {i}: {str(exc)[:70]}", flush=True); continue
        ec.append((r["ec_auto"], bool(j["only_says_what_npc_could_know"])))
        olr.append((r["olr_auto"], bool(j["asserts_true_answer_without_basis"])))
        raf.append((r["raf_auto"], bool(j["states_rumor_as_established_fact"])))
        fwr.append((r["fwr_auto"], bool(j["states_rumor_as_established_fact"])))
        pj.write(json.dumps({**ctx, "ctrl": r["ctrl"], "auto": {"ec": r["ec_auto"], "olr": r["olr_auto"],
                 "raf": r["raf_auto"], "fwr": r["fwr_auto"]}, "judge": j}) + "\n")
        if (i + 1) % 25 == 0:
            print(f"  judged {i+1}", flush=True)
    pj.close()

    cost = judge.input_tokens / 1e6 * 0.40 + judge.output_tokens / 1e6 * 1.60
    print(f"\njudge calls={judge.calls} in={judge.input_tokens} out={judge.output_tokens} cost=${cost:.3f}")
    print("\n=== auto-metric vs independent LLM judge (agreement, Cohen kappa) ===")
    print(f"  {'property':12s}{'n':>5}{'%agree':>9}{'kappa':>8}   (auto base rate)")
    for name, pairs in (("EC", ec), ("OLR", olr), ("RAF", raf), ("FWR", fwr)):
        po, k, n = kappa(pairs)
        base = sum(1 for a, _ in pairs if a) / max(1, n)
        print(f"  {name:12s}{n:>5}{po*100:>8.1f}%{k:>8.2f}   {base:.2f}")

    summ = {name: dict(zip(("agreement", "kappa", "n"), kappa(p)))
            for name, p in (("EC", ec), ("OLR", olr), ("RAF", raf), ("FWR", fwr))}
    json.dump(summ, open(f"{OUT}/metric_validity_results.json", "w"), indent=2)


if __name__ == "__main__":
    main()
